def seed():
    """将字谜批量写入数据库"""
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()

    # 确保教材记录存在
    textbooks_needed = set()
    for _, _, _, grade in RIDDLES:
        for term in [1, 2]:
            textbooks_needed.add(("人教版", grade, term))

    existing_textbooks = {(t.name, t.grade, t.term): t for t in db.query(Textbook).all()}
    for name, grade, term in textbooks_needed:
        key = (name, grade, term)
        if key not in existing_textbooks:
            db.add(Textbook(name=name, grade=grade, term=term))
    db.flush()

    # 重新获取 textbook 映射
    textbook_map = {}
    for t in db.query(Textbook).all():
        textbook_map[(t.name, t.grade, t.term)] = t.id

    # 插入谜题（去重）
    added = 0
    skipped = 0
    for question, answer, difficulty, grade in RIDDLES:
        # 跳过已存在的谜题
        existing = db.query(Riddle).filter(
            Riddle.question == question,
            Riddle.answer == answer
        ).first()
        if existing:
            skipped += 1
            continue

        # 关联 textbook（取该年级上学期的 textbook_id）
        textbook_id = textbook_map.get(("人教版", grade, 1))

        riddle = Riddle(
            question=question,
            answer=answer,
            difficulty=difficulty,
            grade=grade,
            source="manual",
            textbook_id=textbook_id
        )
        db.add(riddle)
        added += 1

    db.commit()
    db.close()
    print(f"谜题入库完成：新增 {added} 条，跳过已有 {skipped} 条")


if __name__ == "__main__":
    seed()
